/** Preset UI theme definitions for light and dark modes */

export interface UIThemeColors {
  background: string
  foreground: string
  muted: string
  'muted-foreground': string
  accent: string
  'accent-foreground': string
  border: string
  primary: string
  'primary-foreground': string
  secondary: string
  'secondary-foreground': string
  destructive: string
  'destructive-foreground': string
  popover: string
  'popover-foreground': string
  ring: string
  sidebar: string
  'sidebar-foreground': string
  'sidebar-border': string
  brand: string
  'brand-soft': string
  'brand-muted': string
  'brand-fg': string
  tint: string
  'tint-soft': string
  'tint-muted': string
  'tint-fg': string
  canvas: string
  'canvas-muted': string
  'scrollbar-thumb': string
}

export interface UICodeThemeColors {
  bg: string
  fg: string
  muted: string
  gutter: string
  border: string
  selection: string
  line: string
  caret: string
  'syntax-keyword': string
  'syntax-string': string
  'syntax-number': string
  'syntax-comment': string
  'syntax-function': string
  'syntax-type': string
  'syntax-variable': string
  'syntax-operator': string
  'syntax-constant': string
  'syntax-meta': string
  'syntax-invalid': string
  'diff-added': string
  'diff-removed': string
  'diff-meta': string
  'diff-hunk': string
}

export interface UITheme {
  id: string
  name: string
  mode: 'light' | 'dark'
  /** Representative color shown in the selector badge */
  preview: string
  colors: UIThemeColors
}

