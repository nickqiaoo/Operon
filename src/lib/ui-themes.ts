/** Apply a UI theme's colors as CSS custom properties on :root */
export function applyUIThemeColors(theme: UITheme) {
  const root = document.documentElement
  for (const [key, value] of Object.entries(theme.colors)) {
    if (key === 'scrollbar-thumb') {
      root.style.setProperty(`--${key}`, value)
    } else {
      root.style.setProperty(`--color-${key}`, value)
    }
  }
  const codeColors = getCodeColorsForTheme(theme)
  for (const [key, value] of Object.entries(codeColors)) {
    root.style.setProperty(`--code-${key}`, value)
  }
}

/** Remove all inline theme overrides so CSS defaults take effect */
export function clearUIThemeColors() {
  const root = document.documentElement
  for (const key of COLOR_KEYS) {
    if (key === 'scrollbar-thumb') {
      root.style.removeProperty(`--${key}`)
    } else {
      root.style.removeProperty(`--color-${key}`)
    }
  }
  for (const key of CODE_COLOR_KEYS) {
    root.style.removeProperty(`--code-${key}`)
  }
}
